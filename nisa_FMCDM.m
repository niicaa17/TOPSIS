fuzzy.C  = [0.25 0.5 0.75];
fuzzy.T  = [0.5 0.75 1];
fuzzy.ST = [0.75 1 1];

fuzzy.SK = fuzzy.SR;
fuzzy.K  = fuzzy.R;
fuzzy.B  = fuzzy.T;
fuzzy.SB = fuzzy.ST;

%% ===============================
% INPUT RATING KEPENTINGAN KRITERIA
% ===============================
disp('Input Rating Kepentingan Kriteria (SR/R/C/T/ST)');
W = zeros(nKrit,3);

for j = 1:nKrit
    label = input(['Bobot ',Kriteria{j},' : '],'s');
    W(j,:) = fuzzy.(label);
end

%% ===============================
% INPUT KECOCOKAN ALTERNATIF
% ===============================
disp('Input Rating Kecocokan Alternatif (SK/K/C/B/SB)');
S = zeros(nAlt,nKrit,3);

for i = 1:nAlt
    disp(['Alternatif : ',Alternatif{i}])
    for j = 1:nKrit
        label = input(['  Kriteria ',Kriteria{j},' : '],'s');
        S(i,j,:) = fuzzy.(label);
    end
end

%% ===============================
% AGREGASI FUZZY (MEAN)
% ===============================
F = zeros(nAlt,3);

for i = 1:nAlt
    for j = 1:nKrit
        F(i,:) = F(i,:) + squeeze(S(i,j,:))' .* W(j,:);
    end
    F(i,:) = F(i,:) / nKrit;
end

%% ===============================
% NILAI TOTAL INTEGRAL (alpha = 0.5)
% ===============================
alpha = 0.5;
TI = (1/2)*( alpha*F(:,3) + F(:,2) + (1-alpha)*F(:,1));

%% ===============================
% OUTPUT HASIL
% ===============================
disp(' ');
disp('Agregasi Fuzzy (Nilai Y Q Z)untuk alternatif A1, A2, dan A3:');
disp(F')

disp('Nilai Total Integral:');
for i = 1:nAlt
    fprintf('%s : %.4f\n', Alternatif{i}, TI(i));
end

[maxVal, idx] = max(TI);

disp(' ');
disp('Alternatif Terbaik:');
fprintf('%s (nilai = %.4f)\n', Alternatif{idx}, maxVal);
