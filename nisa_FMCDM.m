Judul Penelitian:

Implementasi Algoritma Fuzzy C-Means Clustering untuk Pembangkitan Aturan Fuzzy pada Pengelompokan Tingkat Risiko Penyakit Kanker Payudara

? Tujuan Penelitian:

Penelitian ini bertujuan untuk:

Mengembangkan metode otomatis untuk pembangkitan aturan fuzzy dalam mengelompokkan tingkat risiko kanker payudara (jinak atau ganas).

Meningkatkan akurasi diagnosis kanker payudara menggunakan pendekatan Fuzzy C-Means (FCM) dibandingkan interpretasi manual hasil mammogram.

Menentukan jumlah cluster ideal yang mampu menghasilkan tingkat konvergensi dan akurasi terbaik.

Membantu proses pengambilan keputusan medis dengan sistem inferensi fuzzy model Sugeno orde-satu.

?? Algoritma Clustering Fuzzy yang Digunakan:

Algoritma: Fuzzy C-Means (FCM) Clustering

Karakteristik:

Setiap data memiliki derajat keanggotaan pada masing-masing cluster (tidak bersifat kaku seperti K-Means).

FCM mencari pusat cluster (centroid) yang meminimalkan fungsi objektif berdasarkan jarak antara data dan pusat cluster dengan pembobot fuzzy.

Proses umum:

Inisialisasi jumlah cluster (c).

Menghitung derajat keanggotaan setiap data terhadap tiap cluster.

Memperbarui pusat cluster berdasarkan bobot keanggotaan.

Mengulang hingga hasil konvergen (perubahan kecil).

Hasil akhir digunakan untuk pembentukan aturan fuzzy otomatis.

? Jumlah Cluster dan Kategori:

Jumlah cluster ideal yang terpilih: 2 (konvergen).

Kategori hasil cluster:

Cluster 1 ? Risiko rendah / Jinak

Cluster 2 ? Risiko tinggi / Ganas

? Variabel yang Digunakan untuk Clustering:

Penelitian menggunakan Mammographic Mass Data Set dari UCI Machine Learning Repository.
Dataset ini berisi beberapa fitur yang berkaitan dengan karakteristik massa pada mammogram.

Variabel (fitur) utama yang digunakan:

No	Nama Variabel	Deskripsi	Tipe Data
1	BI-RADS Assessment	Penilaian tingkat risiko radiologi (1–5)	Numerik
2	Age	Usia pasien	Numerik
3	Shape	Bentuk massa (oval, lobular, irregular, round)	Kategorikal (diubah ke numerik untuk clustering)
4	Margin	Tepi massa (circumscribed, microlobulated, obscured, ill-defined, spiculated)	Kategorikal (numerik hasil konversi)
5	Density	Kerapatan jaringan massa	Kategorikal (numerik hasil konversi)
6	Severity	Label hasil diagnosis (benign/jinak atau malignant/ganas)	Kategorikal (target evaluasi, bukan fitur input)

?? Untuk proses clustering, variabel 1–5 digunakan sebagai input variabel, sedangkan variabel 6 digunakan untuk evaluasi hasil cluster (akurasi).

? Hasil Utama:

Jumlah cluster ideal: 2

Model fuzzy: Sugeno orde-satu

Akurasi sistem:

Rata-rata akurasi = 78%

Akurasi tertinggi = 84% (pada jumlah aturan = 2)
